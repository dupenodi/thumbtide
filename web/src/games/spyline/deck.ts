/** Every deck word with its clue words, in the order written. */
export const DECK: ReadonlyMap<string, readonly string[]> = (() => {
  const m = new Map<string, string[]>();
  for (const line of SRC.split("\n")) {
    const i = line.indexOf(":");
    if (i < 0) continue;
    const word = line.slice(0, i).trim().toLowerCase();
    if (!word) continue;
    const clues = line.slice(i + 1).trim().toLowerCase().split(/\s+/).filter((c) => c && c !== word);
    const old = m.get(word);
    m.set(word, [...new Set([...(old ?? []), ...clues])]);
  }
  return m;
})();

export const WORDS: readonly string[] = [...DECK.keys()];
